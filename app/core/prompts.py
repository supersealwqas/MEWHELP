# 决策阶段的完整系统提示：人设守则 + 决策期工具规则。
CUSTOMER_SERVICE_SYSTEM: str = CUSTOMER_SERVICE_PERSONA + TOOL_DECISION_RULES

# 客服多轮对话 ChatPromptTemplate
# 系统提示词置顶，多轮历史消息通过 MessagesPlaceholder 动态注入
